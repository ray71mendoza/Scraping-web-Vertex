let currentIndex = 0;

/**
 * Returns a random User-Agent string from the pool.
 */
export function getRandomUserAgent(): string {
  const idx = Math.floor(Math.random() * USER_AGENTS.length);
  return USER_AGENTS[idx];
}

/**
 * Returns User-Agent strings in round-robin order.
 */
export function getNextUserAgent(): string {
  const ua = USER_AGENTS[currentIndex % USER_AGENTS.length];
  currentIndex++;
  return ua;
}

/**
 * Returns all available User-Agent strings.
 */
export function getAllUserAgents(): string[] {
  return [...USER_AGENTS];
}
